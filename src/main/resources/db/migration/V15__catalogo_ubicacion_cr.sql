-- FK compuesta desde cliente/empresa hacia distrito, agregada como NOT VALID:
-- se aplica de inmediato a toda escritura nueva (INSERT/UPDATE) sin escanear
-- ni fallar contra filas ya existentes -- hay datos reales en producción que
-- no se pueden romper con este cambio. Las filas viejas quedan sin verificar
-- hasta que alguien corra VALIDATE CONSTRAINT explícitamente (solo lee, no
-- bloquea ni escribe nada).
--
-- El CHECK "todo o nada" que ya existe en cliente (V4) queda intacto: FK
-- MATCH SIMPLE (default de Postgres) no exige nada cuando alguna columna es
-- NULL, así que ambos constraints conviven sin conflicto.
--
-- Fuera de alcance de esta migración: empresa hoy no tiene ningún CHECK
-- "todo o nada" (cliente sí) -- no se agrega aquí porque, con datos reales,
-- correr ese CHECK retroactivo tiene el mismo riesgo que esta FK y es una
-- decisión aparte de "agregar el catálogo".
ALTER TABLE cliente
  ADD CONSTRAINT fk_cliente_ubicacion
  FOREIGN KEY (codigo_provincia, canton, distrito)
  REFERENCES distrito (provincia_codigo, canton_codigo, codigo)
  NOT VALID;

ALTER TABLE empresa
  ADD CONSTRAINT fk_empresa_ubicacion
  FOREIGN KEY (codigo_provincia, canton, distrito)
  REFERENCES distrito (provincia_codigo, canton_codigo, codigo)
  NOT VALID;

