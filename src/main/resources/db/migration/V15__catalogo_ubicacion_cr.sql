-- Catálogo de ubicación de Costa Rica (provincia/cantón/distrito).
--
-- Clave natural como PK compuesta (sin id autoincremental): la combinación
-- provincia/cantón/distrito no puede duplicarse estructuralmente, sin
-- importar cuántas veces se vuelva a aplicar esta migración (Flyway solo la
-- corre una vez de cualquier forma). ON CONFLICT DO NOTHING se agrega de
-- todas formas como defensa adicional, sin costo.
--
-- Valores del seed tomados de docs/proyecto-referencia/erp_spring_manager/
-- database/seeds/{01_cat_provincia_cr,02_cat_canton_cr,03_cat_distrito_cr}.sql
-- (códigos oficiales de Costa Rica) -- se reescribe únicamente el mecanismo
-- SQL (MySQL "INSERT ... ON DUPLICATE KEY UPDATE" -> Postgres "INSERT ... ON
-- CONFLICT DO NOTHING"), no los datos.

CREATE TABLE provincia (
    codigo VARCHAR(1)  PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL
);

CREATE TABLE canton (
    provincia_codigo VARCHAR(1)   NOT NULL REFERENCES provincia(codigo),
    codigo            VARCHAR(2)  NOT NULL,
    nombre            VARCHAR(100) NOT NULL,
    PRIMARY KEY (provincia_codigo, codigo)
);

CREATE TABLE distrito (
    provincia_codigo VARCHAR(1)   NOT NULL,
    canton_codigo     VARCHAR(2)  NOT NULL,
    codigo            VARCHAR(2)  NOT NULL,
    nombre            VARCHAR(100) NOT NULL,
    PRIMARY KEY (provincia_codigo, canton_codigo, codigo),
    FOREIGN KEY (provincia_codigo, canton_codigo) REFERENCES canton (provincia_codigo, codigo)
);

